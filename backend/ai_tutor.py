"""
Модуль ИИ-Наставника (AI Tutor) и чат-бота Копилота.
Анализирует тренды телеметрии для прогнозирования аварий ДО их совершения
и отвечает на вопросы оператора по технологическому регламенту.
"""
from backend.schemas import SimulatorState, DiagnosticEvent

class AITutor:
    def __init__(self):
        self.last_predicted_event = ""

    def predict_incidents(self, state: SimulatorState) -> str:
        """
        Прогнозирование аварийных ситуаций до их фактического наступления.
        Анализирует динамику роста температур/давлений.
        """
        # 1. Прогноз по давлению верха К-1
        if state.atm_column.top_pressure > 0.30 and state.atm_column.top_pressure < 0.45:
            return "[ПРОГНОЗ ИИ] Рост давления верха К-1. При сохранении тренда через 30 секунд давление достигнет 0.45 МПа и сработает аварийная блокировка ПАЗ-2 (отсечка топлива печи)."
            
        # 2. Прогноз по температуре труб П-1
        if state.furnace.tube_skin_temp > 450.0 and state.furnace.tube_skin_temp < 500.0:
            return "[ПРОГНОЗ ИИ] Температура змеевиков печи П-1 растет слишком быстро. Прогноз прогара труб через 1 минуту. Срочно снизьте расход топливного газа!"

        # 3. Прогноз по уровню ЭЛОУ
        elou_level = getattr(state.desalter, "phase_level_mm", 4000.0)
        if elou_level < 3700.0 and elou_level > 3500.0:
            return "[ПРОГНОЗ ИИ] Уровень раздела фаз в дегидраторе падает. Прогноз отключения напряжения ЭЛОУ через 15 секунд (блокировка ПАЗ-1 при < 3500 мм)."
            
        return ""

    def answer_operator_question(self, question: str, state: SimulatorState) -> str:
        """
        Ответ чат-бота Наставника на вопросы оператора по техрегламенту АВТ-5.
        Использует локальную базу правил.
        """
        q = question.lower()
        
        if "давление" in q or "к-1" in q:
            return (
                "Согласно регламенту (раздел 3.5), рабочее давление верха К-1 составляет 1.0 - 4.5 кгс/см2. "
                "При повышении давления до 4.5 кгс/см2 срабатывает сигнализация PRSA 204, а при 4.8 кгс/см2 — "
                "блокировка ПАЗ-2, перекрывающая подачу газа и жидкого топлива на форсунки печей П-1, П-2, П-3."
            )
            
        if "печь" in q or "змеевик" in q or "п-1" in q:
            return (
                "Регламент печей П-1..П-3 (раздел 7.7.1.12): Не допускать лизания труб пламенем форсунок. "
                "Критическая температура стенки змеевика — 500°С. Скорость коксообразования экспоненциально "
                "растет выше 450°С, что ведет к риску прогара труб."
            )
            
        if "элоу" in q or "соль" in q or "обессоливание" in q:
            return (
                "Регламент ЭЛОУ (раздел 3.3): Норма соли после обессоливания — не более 5 мг/л (ГОСТ 21534), "
                "воды — не более 0.15%. Напряжение на электродах Э-1..Э-6 должно составлять 11, 16.5 или 22 кВ. "
                "Уровень раздела фаз должен быть не менее 3500 мм (блокировка ПАЗ-1)."
            )
            
        if "вакуум" in q or "к-2" in q:
            return (
                "Регламент вакуумной колонны К-2 (раздел 3.5): Давление верха составляет 0.2 - 1.0 кгс/см2 абс. "
                "Уровень куба К-2 должен поддерживаться выше 15% (по LRSA 604А) во избежание срыва мазутных насосов Н-4, Н-32."
            )
            
        if "сизод" in q or "противогаз" in q or "сиз" in q:
            return (
                "Таблица №11: Все операции на установке АВТ-5/5 требуют наличия каски, защитных очков и спецобуви. "
                "При дренировании подтоварной воды и обслуживании ЭЛОУ обязателен фильтрующий противогаз марки БКФ (зеленая коробка)."
            )
            
        return (
            "Запрос принят. Рекомендую проверить текущие параметры SCADA: расходы сырья, температуры змеевиков печи "
            "и уровни раздела фаз в дегидраторах. Все действия пишите в журнал."
        )
